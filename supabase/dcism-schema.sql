-- Enrolla DCISM PostgreSQL schema.
-- Run this first in the empty DCISM database.
-- This intentionally excludes Supabase Auth, RLS, RPC, and Realtime objects.

create extension if not exists pgcrypto;

create table if not exists users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  password_hash text not null,
  email_verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists programs (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code ~ '^[A-Z0-9]+$'),
  name text not null,
  department text not null,
  description text not null default '',
  subject_codes text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists profiles (
  id uuid primary key references users(id) on delete cascade,
  student_id text unique,
  username text unique,
  full_name text not null,
  email text,
  contact text,
  program_code text references programs(code) on update cascade on delete set null,
  year_level text,
  enrollment_status text not null default 'Not Enrolled'
    check (enrollment_status in ('Enrolled','Pending','Not Enrolled','Irregular')),
  role text not null default 'student'
    check (role in ('student','admin','super_admin')),
  is_demo boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists courses (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  title text not null,
  description text not null default '',
  instructor text not null,
  building text,
  room text,
  schedule_text text not null,
  units integer not null check (units between 1 and 12),
  program_code text references programs(code) on update cascade on delete set null,
  max_capacity integer not null check (max_capacity > 0),
  enrolled_count integer not null default 0,
  status text not null default 'available' check (status in ('available','enrolled','closed')),
  course_type text not null default 'Core',
  days text[] not null default '{}',
  start_hour numeric(4,2) not null default 0,
  duration numeric(4,2) not null default 1,
  color text,
  prerequisite text,
  topics text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists enrollment_settings (
  id integer primary key default 1 check (id = 1),
  mode text not null default 'manual' check (mode in ('manual','automatic')),
  manual_status text not null default 'Open' check (manual_status in ('Open','Closed')),
  start_date_time timestamptz,
  end_date_time timestamptz,
  academic_year text not null default '2026 - 2027',
  semester text not null default '1st Semester (Fall)',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists enrollments (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references profiles(id) on delete cascade,
  course_id uuid not null references courses(id) on delete restrict,
  program_code text references programs(code) on update cascade on delete set null,
  status text not null default 'Pending'
    check (status in ('Pending','Approved','Rejected','Cancelled')),
  date_submitted timestamptz not null default now(),
  decided_at timestamptz,
  decided_by uuid references profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student_id, course_id)
);

create table if not exists special_requests (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references profiles(id) on delete cascade,
  type text not null,
  course_id uuid references courses(id) on delete set null,
  units integer,
  reason text not null,
  status text not null default 'Pending',
  admin_remark text not null default '',
  decided_by uuid references profiles(id) on delete set null,
  date_submitted timestamptz not null default now(),
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references profiles(id) on delete set null,
  actor text not null,
  role text,
  module text not null,
  action text not null,
  details text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists notifications (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references profiles(id) on delete cascade,
  icon text not null default 'info',
  text text not null,
  target text,
  unread boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists student_profile_data (
  profile_id uuid primary key references profiles(id) on delete cascade,
  first_name text,
  middle_name text,
  last_name text,
  phone text,
  date_of_birth date,
  campus text,
  address text,
  guardian text,
  avatar_url text,
  medical_cleared boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists admin_signup_codes (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  created_by uuid not null references profiles(id) on delete cascade,
  used_at timestamptz,
  used_by uuid references profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists profiles_student_id_idx on profiles(student_id);
create index if not exists profiles_program_code_idx on profiles(program_code);
create index if not exists courses_program_code_idx on courses(program_code);
create index if not exists enrollments_student_idx on enrollments(student_id);
create index if not exists enrollments_course_idx on enrollments(course_id);
create index if not exists special_requests_student_idx on special_requests(student_id);
create index if not exists notifications_profile_idx on notifications(profile_id, created_at desc);
create index if not exists audit_logs_created_at_idx on audit_logs(created_at desc);

